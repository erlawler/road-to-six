// Generates lib/mcp-app-view-html.mjs from app/mcp/forecast-card.html.
//
// The card is authored as a real HTML file so it can be opened, reviewed and
// tested in a browser. The Worker and the Node tests need it as a module
// export, so this script writes that module. Run it after editing the HTML:
//
//   npm run mcp:view            writes the module
//   npm run mcp:view -- --check exits 1 when the module is out of date

import { readFile, writeFile } from "node:fs/promises";

const source = new URL("../app/mcp/forecast-card.html", import.meta.url);
const target = new URL("../lib/mcp-app-view-html.mjs", import.meta.url);

export async function renderViewModule() {
  const html = (await readFile(source, "utf8")).trimEnd();
  return [
    "// Generated by scripts/build-mcp-app-view.mjs from app/mcp/forecast-card.html.",
    "// Do not edit by hand. Run `npm run mcp:view` after changing the HTML source.",
    `export const FORECAST_CARD_HTML = ${JSON.stringify(html)};`,
    "",
  ].join("\n");
}

if (import.meta.url === new URL(process.argv[1], "file:").href) {
  const expected = await renderViewModule();
  if (process.argv.includes("--check")) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== expected) {
      console.error("lib/mcp-app-view-html.mjs is out of date. Run `npm run mcp:view`.");
      process.exit(1);
    }
    console.log("lib/mcp-app-view-html.mjs matches app/mcp/forecast-card.html");
  } else {
    await writeFile(target, expected);
    console.log(`Wrote lib/mcp-app-view-html.mjs (${Buffer.byteLength(expected)} bytes)`);
  }
}
